import assert from 'node:assert/strict';
import fs from 'node:fs';
import {selectPlan,makeQuestions,scoreFor,updateProgress,shiftDate,normalize,consecutiveDays} from '../js/engine.js';
const words=JSON.parse(fs.readFileSync(new URL('../data/words.json',import.meta.url),'utf8'));
assert.ok(words.length>=300);
assert.equal(new Set(words.map(w=>w.word.toLowerCase())).size,words.length);
const initial=selectPlan(words,{},50,'2026-11-20');assert.equal(initial.length,5);
const questions=makeQuestions(initial,words,'learn');assert.equal(questions.length,10);
assert.equal(questions.filter(q=>q.type==='choice').length+questions.filter(q=>q.type==='blank').length,5);
const id=initial[0],p=updateProgress({id},'2026-11-20',{correct:0,mistakes:2,total:2},'learn');
assert.equal(p.weak,true);assert.equal(p.dueDate,'2026-11-21');
const reviewed=updateProgress(p,'2026-11-21',{correct:2,mistakes:0,total:2},'review');
assert.equal(reviewed.weak,false);
const carried=selectPlan(words,{[id]:reviewed},50,'2026-11-21',[id]);assert.equal(carried[0],id);assert.equal(carried.length,5);
const stats=scoreFor(id,{answers:[{wordId:id,correct:false},{wordId:id,correct:true}]});assert.deepEqual(stats,{mistakes:1,correct:1,total:2});
assert.equal(shiftDate('2026-12-31',1),'2027-01-01');
assert.equal(normalize('  Root   Cause. '),'root cause');
assert.equal(consecutiveDays([{id:'2026-11-19',completed:true},{id:'2026-11-20',completed:true}],'2026-11-20'),2);
console.log('All VocabLab engine tests passed.');
